  assert.ok(f.provider.verifyAccessToken(owned.accessToken, { resource }));
  const digest = createHash('sha256').update(owned.refreshToken).digest('hex');
  const ownedRow = f.store.db.prepare('SELECT * FROM oauth_provider_refresh_tokens WHERE token_hash=?').get(digest);
  const roomBefore = f.store.room('commons');
  const filename = join(directory, 'new-data.sqlite');
  await backup(f.store.db, filename);
  f.store.close(); open = null;
  const old = new OldStore(filename); open = old;
  old.now = () => f.store.now();
  assert.deepEqual(old.room('commons'), roomBefore, 'old code reads the exact new-code room');
  const providerFor = (store, factory, validate) => factory({ db: store.db, clock: () => store.now(), isAccountActive: id => store.db.prepare('SELECT active FROM accounts WHERE id=?').get(id)?.active === 1, isBindingActive: (id, value) => Boolean(validate(store, id, value)) });
