  assert.ok(p.verifyAccessToken(f.tokens.accessToken, { resource }), 'existing legacy access survives rollback');
  const rotated = p.refresh({ refreshToken: f.tokens.refreshToken, clientId, resource });
  assert.ok(p.verifyAccessToken(rotated.accessToken, { resource }), 'legacy refresh survives rollback');
  assert.equal(p.verifyAccessToken(owned.accessToken, { resource }), null, 'new principal fails closed in old code');
  assert.throws(() => p.refresh({ refreshToken: owned.refreshToken, clientId, resource }), /agent connection/);
  assert.deepEqual(old.db.prepare('SELECT * FROM oauth_provider_refresh_tokens WHERE token_hash=?').get(digest), ownedRow, 'unsupported grant is preserved, not revoked or consumed');
